import assert from 'node:assert/strict';
import test from 'node:test';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
import vm from 'node:vm';
test('snapshot refresh synchronizes routes without overriding manual or Agent camera framing',async()=>{
 const source=await readFile(new URL('../components/TravelMap.tsx',import.meta.url),'utf8');
 const start=source.indexOf('const framingState =');
 assert.ok(start>=0,'map tracks framing independently from refreshed trip objects');
 const body=source.slice(start,source.indexOf('// 重新导出类型',start));
 const js=ts.transpileModule(body,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.None}}).outputText;
 const context={};vm.createContext(context);vm.runInContext(js+';globalThis.syncTrip=syncTrip;',context);
 let fits=0,routes=0;
 const engine={fitToStops:()=>fits++,setRoutes:()=>routes++};
 const point={id:'stop_a',longitude:2,latitude:48};
 const trip={id:'trip_a',name:'Paris',stops:[point],segments:[]};
 context.syncTrip(engine,trip);
 assert.equal(fits,1);
 context.syncTrip(engine,{...trip,name:'Renamed',revision:2});
 context.syncTrip(engine,{...trip,segments:[{id:'route',route:{coordinates:[[2,48],[3,49]]}}]});
 context.syncTrip(engine,{...trip,stops:[point,{id:'stop_b',longitude:3,latitude:49}]});
 assert.equal(fits,1,'edits preserve explicit focus; presentation commands control subsequent framing');
 assert.equal(routes,4,'every snapshot still synchronizes route overlays');
 context.syncTrip(engine,{...trip,id:'trip_b'});assert.equal(fits,2);
 context.syncTrip(engine,{...trip,id:'trip_b',stops:[]});assert.equal(fits,2);
 context.syncTrip(engine,{...trip,id:'trip_b'});assert.equal(fits,3,'first stop in an empty map becomes visible');
 const newEngine={fitToStops:()=>fits++,setRoutes:()=>{}};
 context.syncTrip(newEngine,trip);assert.equal(fits,4,'a recreated map gets initial framing');
});
